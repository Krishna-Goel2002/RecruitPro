-- WP-PLAT (plan v2, Section 3.3): multi-instance safety, work-sample files and cancellation, scorecard revisions,
-- interview calendar sequence, e-mail attachments. H2-compatible (no partial indexes, no ON CONFLICT).

-- Background jobs: "<TYPE>:<entityId>" while PENDING, NULL otherwise. The unique constraint makes a concurrent
-- duplicate enqueue fail instead of creating a second PENDING job (NULLs never collide).
ALTER TABLE background_jobs ADD COLUMN dedupe_key VARCHAR(120) NULL;

UPDATE background_jobs SET dedupe_key = job_type || ':' || CAST(entity_id AS VARCHAR(20))
WHERE status = 'PENDING'
  AND id IN (SELECT MIN(b.id) FROM background_jobs b WHERE b.status = 'PENDING' GROUP BY b.job_type, b.entity_id);

ALTER TABLE background_jobs ADD CONSTRAINT uk_background_jobs_dedupe_key UNIQUE (dedupe_key);

-- Notification sender row claims (several backend instances) and one optional e-mail attachment (ICS invites).
ALTER TABLE notifications ADD COLUMN claimed_by VARCHAR(80) NULL;
ALTER TABLE notifications ADD COLUMN claimed_until TIMESTAMP NULL;
ALTER TABLE notifications ADD COLUMN attachment_name VARCHAR(120) NULL;
ALTER TABLE notifications ADD COLUMN attachment_content_type VARCHAR(120) NULL;
ALTER TABLE notifications ADD COLUMN attachment_content TEXT NULL;

-- Shared fixed-window rate-limit counters (app.rate-limit.store=database).
CREATE TABLE rate_limit_buckets (
    bucket_key VARCHAR(200) NOT NULL PRIMARY KEY,
    window_start TIMESTAMP NOT NULL,
    hit_count INTEGER DEFAULT 0 NOT NULL
);

CREATE INDEX idx_rate_limit_buckets_window ON rate_limit_buckets (window_start);

-- Work samples: HR cancellation (status CANCELLED is already allowed by chk_work_sample_assignments_status).
ALTER TABLE work_sample_assignments ADD COLUMN cancelled_at TIMESTAMP NULL;
ALTER TABLE work_sample_assignments ADD COLUMN cancelled_by_user_id BIGINT NULL;
ALTER TABLE work_sample_assignments ADD COLUMN cancel_reason VARCHAR(1000) NULL;
ALTER TABLE work_sample_assignments ADD CONSTRAINT fk_work_sample_assignments_cancelled_by
    FOREIGN KEY (cancelled_by_user_id) REFERENCES users (id) ON DELETE SET NULL;

-- Files submitted with a work sample (max 3 per assignment, 20 MB each, enforced by the service).
CREATE TABLE work_sample_submission_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_work_sample_submission_files_assignment
        FOREIGN KEY (assignment_id) REFERENCES work_sample_assignments (id) ON DELETE CASCADE,
    CONSTRAINT chk_work_sample_submission_files_size CHECK (size_bytes > 0)
);

CREATE INDEX idx_work_sample_submission_files_assignment ON work_sample_submission_files (assignment_id);

-- Scorecard edit history: the version that was replaced, as JSON, with the editor.
CREATE TABLE interview_scorecard_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scorecard_id BIGINT NOT NULL,
    revised_by BIGINT NULL,
    snapshot_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_interview_scorecard_revisions_scorecard
        FOREIGN KEY (scorecard_id) REFERENCES interview_scorecards (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_scorecard_revisions_user FOREIGN KEY (revised_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_interview_scorecard_revisions_scorecard ON interview_scorecard_revisions (scorecard_id);

-- ICS SEQUENCE of the interview's calendar event (incremented on every reschedule and on cancellation).
ALTER TABLE interviews ADD COLUMN ics_sequence INTEGER DEFAULT 0 NOT NULL;
