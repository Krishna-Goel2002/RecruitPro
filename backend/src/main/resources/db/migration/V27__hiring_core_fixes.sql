-- R2-H02: a recruiter's claim verification is per organisation. candidate_claims kept one verification in single
-- columns, so a second organisation's verification overwrote the first one. One row per (claim, organisation) now;
-- this table is the only decision input. candidate_claims.tier / verified_by_user_id / verified_at /
-- verification_note stay as a deprecated, derived candidate-facing summary of all rows (any corroboration wins,
-- else the latest rejection; CandidateClaim.summarize, integration pass). tier: CORROBORATED or SELF_CLAIMED (rejected).
CREATE TABLE candidate_claim_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    tier VARCHAR(30) NOT NULL,
    verified_by_user_id BIGINT NULL,
    verified_at TIMESTAMP NOT NULL,
    verification_note VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_claim_verifications_claim FOREIGN KEY (claim_id) REFERENCES candidate_claims (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verifications_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verifications_user FOREIGN KEY (verified_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uk_claim_verifications_claim_org UNIQUE (claim_id, organization_id),
    CONSTRAINT chk_claim_verifications_tier CHECK (tier IN ('SELF_CLAIMED', 'CORROBORATED'))
);

CREATE INDEX idx_claim_verifications_organization ON candidate_claim_verifications (organization_id);

-- Existing verifications belong to the verifier's organisation.
INSERT INTO candidate_claim_verifications (claim_id, organization_id, tier, verified_by_user_id, verified_at,
                                           verification_note, created_at, updated_at)
SELECT c.id, u.organization_id,
       CASE WHEN c.tier = 'SELF_CLAIMED' THEN 'SELF_CLAIMED' ELSE 'CORROBORATED' END,
       c.verified_by_user_id, c.verified_at, c.verification_note, c.verified_at, c.verified_at
FROM candidate_claims c
JOIN users u ON u.id = c.verified_by_user_id
WHERE c.verified_at IS NOT NULL AND u.organization_id IS NOT NULL;

-- R2-H01: OTHER requirements are never scored automatically, so as knockouts they held every applicant of the job
-- in MUST_HAVES_UNVERIFIED. They are never knockouts any more (the backend also ignores the flag for OTHER).
UPDATE job_requirements SET knockout = FALSE WHERE requirement_type = 'OTHER' AND knockout = TRUE;
