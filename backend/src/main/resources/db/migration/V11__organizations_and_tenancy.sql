-- D3: multi-tenancy by organisation. Staff users belong to exactly one organisation; candidates have none.

CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(80) NOT NULL,
    blind_review BOOLEAN DEFAULT TRUE NOT NULL,
    share_verification_status BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_organizations_slug UNIQUE (slug)
);

ALTER TABLE users ADD COLUMN organization_id BIGINT NULL;
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP NULL;
ALTER TABLE users ADD COLUMN failed_login_count INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN locked_until TIMESTAMP NULL;
ALTER TABLE users ADD COLUMN password_changed_at TIMESTAMP NULL;
ALTER TABLE users ADD COLUMN deleted_at TIMESTAMP NULL;
ALTER TABLE users ADD CONSTRAINT fk_users_organization FOREIGN KEY (organization_id) REFERENCES organizations (id);

ALTER TABLE jobs ADD COLUMN organization_id BIGINT NULL;
ALTER TABLE jobs ADD CONSTRAINT fk_jobs_organization FOREIGN KEY (organization_id) REFERENCES organizations (id);

-- Backfill: existing installations with staff users or jobs get one organisation called "default".
-- system_metadata holds exactly one 'schema_version' row (V1), so this inserts at most one organisation.
INSERT INTO organizations (name, slug, blind_review, share_verification_status, created_at, updated_at)
SELECT 'Default organisation', 'default', TRUE, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM system_metadata
WHERE property_key = 'schema_version'
  AND (EXISTS (SELECT 1 FROM users WHERE role <> 'CANDIDATE') OR EXISTS (SELECT 1 FROM jobs));

UPDATE users
SET organization_id = (SELECT o.id FROM organizations o WHERE o.slug = 'default')
WHERE role <> 'CANDIDATE';

UPDATE jobs
SET organization_id = (SELECT o.id FROM organizations o WHERE o.slug = 'default');

ALTER TABLE jobs ALTER COLUMN organization_id SET NOT NULL;

CREATE INDEX idx_jobs_organization_status ON jobs (organization_id, status);
CREATE INDEX idx_users_organization ON users (organization_id);

CREATE TABLE invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    invited_by_user_id BIGINT NULL,
    expires_at TIMESTAMP NOT NULL,
    accepted_at TIMESTAMP NULL,
    revoked_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_invitations_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_invitations_organization FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_invitations_invited_by FOREIGN KEY (invited_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_invitations_role CHECK (role IN ('ADMIN', 'HR_MANAGER', 'RECRUITER', 'INTERVIEWER'))
);

CREATE INDEX idx_invitations_org_created ON invitations (organization_id, created_at);
