-- D14 / M15 (plan 3.2, 5.5 and 5.7, WP-BE-C): voluntary equal-opportunity answers are stored apart from the
-- profile, only with consent, deletable by the candidate, never shown to reviewers and reported only in aggregates.
-- Date of birth and gender leave the candidate profile.

CREATE TABLE eeo_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    gender VARCHAR(40) NULL,
    age_band VARCHAR(20) NULL,
    disability VARCHAR(20) NULL,
    social_category VARCHAR(40) NULL,
    consent_given_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_eeo_responses_candidate UNIQUE (candidate_id),
    CONSTRAINT fk_eeo_responses_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_eeo_responses_gender
        CHECK (gender IS NULL OR gender IN ('WOMAN', 'MAN', 'NON_BINARY', 'SELF_DESCRIBE', 'PREFER_NOT')),
    CONSTRAINT chk_eeo_responses_age_band
        CHECK (age_band IS NULL OR age_band IN ('UNDER_25', '25_34', '35_44', '45_54', '55_PLUS', 'PREFER_NOT')),
    CONSTRAINT chk_eeo_responses_disability
        CHECK (disability IS NULL OR disability IN ('YES', 'NO', 'PREFER_NOT')),
    CONSTRAINT chk_eeo_responses_social_category
        CHECK (social_category IS NULL OR social_category IN ('GENERAL', 'OBC', 'SC', 'ST', 'EWS', 'OTHER', 'PREFER_NOT'))
);

ALTER TABLE candidate_profiles DROP COLUMN date_of_birth;
ALTER TABLE candidate_profiles DROP COLUMN gender;
