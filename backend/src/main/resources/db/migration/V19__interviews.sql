-- Structured interviews (plan 3.2 and 5.6, WP-BE-C): one interview kit per job, scheduled interviews with an
-- assigned interviewer, and one scorecard per interview. A rating of 3 or 4 on a requirement-linked question makes
-- that requirement INTERVIEW_VERIFIED (evidence tier 4) at the next match.

CREATE TABLE interview_kits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    questions_json TEXT NOT NULL,
    generated_by VARCHAR(40) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_interview_kits_job UNIQUE (job_id),
    CONSTRAINT fk_interview_kits_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE
);

CREATE TABLE interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    interviewer_user_id BIGINT NOT NULL,
    scheduled_at TIMESTAMP NOT NULL,
    duration_minutes INTEGER NOT NULL,
    location VARCHAR(500) NULL,
    status VARCHAR(20) NOT NULL,
    created_by_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_interviews_application FOREIGN KEY (application_id) REFERENCES applications (id),
    CONSTRAINT fk_interviews_interviewer FOREIGN KEY (interviewer_user_id) REFERENCES users (id),
    CONSTRAINT fk_interviews_created_by FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT chk_interviews_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_interviews_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX idx_interviews_application ON interviews (application_id);
CREATE INDEX idx_interviews_interviewer_scheduled ON interviews (interviewer_user_id, scheduled_at);

CREATE TABLE interview_scorecards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id BIGINT NOT NULL,
    ratings_json TEXT NOT NULL,
    recommendation VARCHAR(20) NOT NULL,
    summary TEXT NULL,
    submitted_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_interview_scorecards_interview UNIQUE (interview_id),
    CONSTRAINT fk_interview_scorecards_interview FOREIGN KEY (interview_id) REFERENCES interviews (id) ON DELETE CASCADE,
    CONSTRAINT chk_interview_scorecards_recommendation
        CHECK (recommendation IN ('STRONG_NO', 'NO', 'YES', 'STRONG_YES'))
);
