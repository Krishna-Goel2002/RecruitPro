-- HR assistant (docs/plan/ASSISTANT_PLAN.md, section 3.2, work package AS-BE). H2- and PostgreSQL-compatible.

-- Privacy switch: when false (the default for new organisations) the assistant uses only the offline planner, even
-- when an LLM provider is configured. The demo organisation ("acme-labs") may use the external model.
ALTER TABLE organizations ADD COLUMN assistant_external_model BOOLEAN DEFAULT FALSE NOT NULL;
UPDATE organizations SET assistant_external_model = TRUE WHERE slug = 'acme-labs';

-- One conversation per thread of a staff user. draft_json (beyond the contract): the job-posting slot-filling state
-- the planner returns ({"kind":"job_posting","fields":{...}}), kept by the backend because the planner is stateless.
CREATE TABLE assistant_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    draft_json TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_assistant_conversations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistant_conversations_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE
);

CREATE INDEX idx_assistant_conversations_user ON assistant_conversations (user_id, updated_at);
CREATE INDEX idx_assistant_conversations_updated ON assistant_conversations (updated_at);

-- Messages: role user or assistant; blocks_json is the JSON array of UI blocks; planner is the planner that answered
-- ("offline", "gemini", ..., "unavailable"); status_trace (beyond the contract) the short "thinking" trace.
CREATE TABLE assistant_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    text TEXT NOT NULL,
    blocks_json TEXT NULL,
    planner VARCHAR(40) NULL,
    status_trace VARCHAR(1000) NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_assistant_messages_conversation
        FOREIGN KEY (conversation_id) REFERENCES assistant_conversations (id) ON DELETE CASCADE,
    CONSTRAINT chk_assistant_messages_role CHECK (role IN ('user', 'assistant'))
);

CREATE INDEX idx_assistant_messages_conversation ON assistant_messages (conversation_id, id);

-- Proposed actions (writes always need a confirmation). Expire 30 minutes after they are proposed.
CREATE TABLE assistant_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    action VARCHAR(40) NOT NULL,
    args_json TEXT NOT NULL,
    preview_json TEXT NULL,
    status VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    result_json TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_assistant_actions_conversation
        FOREIGN KEY (conversation_id) REFERENCES assistant_conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistant_actions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_assistant_actions_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT chk_assistant_actions_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'FAILED'))
);

CREATE INDEX idx_assistant_actions_conversation ON assistant_actions (conversation_id);
CREATE INDEX idx_assistant_actions_user ON assistant_actions (user_id, status);
