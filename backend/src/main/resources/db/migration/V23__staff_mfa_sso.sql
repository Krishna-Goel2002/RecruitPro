-- WP-PLAT (plan v2, Section 3.3): staff TOTP MFA, recovery codes, OIDC single sign-on.
-- H2 (MODE=PostgreSQL) runs this file in tests: no partial indexes, no ON CONFLICT, TEXT for JSON.

-- One TOTP secret per user (AES-GCM ciphertext from SecretCipher, context "mfa:<userId>").
-- enabled_at is NULL while the enrolment waits for its first code; last_used_step is the replay guard.
CREATE TABLE user_mfa (
    user_id BIGINT NOT NULL PRIMARY KEY,
    secret_enc VARCHAR(500) NOT NULL,
    enabled_at TIMESTAMP NULL,
    last_used_step BIGINT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_user_mfa_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- Ten single-use recovery codes per enrolment; only the password-encoder hash is stored.
CREATE TABLE user_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    code_hash VARCHAR(100) NOT NULL,
    used_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_user_recovery_codes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_recovery_codes_user ON user_recovery_codes (user_id);

ALTER TABLE organizations ADD COLUMN require_staff_mfa BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE organizations ADD COLUMN sso_allowed_domains VARCHAR(500) NULL;

-- External identities linked to a staff account (never provisioned automatically).
CREATE TABLE user_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(40) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    email VARCHAR(255) NULL,
    last_login_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_user_identities_provider_subject UNIQUE (provider, subject),
    CONSTRAINT fk_user_identities_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_identities_user ON user_identities (user_id);

-- Pending OIDC authorisation requests: state and nonce are stored as SHA-256 hashes, the PKCE verifier encrypted.
-- Single use (used_at) and valid for 10 minutes.
CREATE TABLE sso_login_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_hash VARCHAR(64) NOT NULL,
    nonce_hash VARCHAR(64) NOT NULL,
    code_verifier_enc VARCHAR(500) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    portal VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_sso_login_states_state UNIQUE (state_hash)
);

CREATE INDEX idx_sso_login_states_expires ON sso_login_states (expires_at);

-- The MFA login step uses single-use tokens of user_tokens (5 minutes).
ALTER TABLE user_tokens DROP CONSTRAINT chk_user_tokens_purpose;
ALTER TABLE user_tokens ADD CONSTRAINT chk_user_tokens_purpose
    CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD', 'MFA_LOGIN', 'MFA_ENROLL'));
