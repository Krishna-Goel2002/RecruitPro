-- Reference requests (plan v2, sections 3.2 and 5; WP-VBE). The referee answers on a public page reached through a
-- one-time link; only the SHA-256 of its token is stored.

CREATE TABLE verification_reference_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    referee_name VARCHAR(200) NOT NULL,
    referee_email VARCHAR(255) NOT NULL,
    relationship VARCHAR(20) NOT NULL,
    employer_name VARCHAR(200) NULL,
    employer_domain VARCHAR(253) NULL,
    claim_refs_json TEXT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) DEFAULT 'SENT' NOT NULL,
    answers_json TEXT NULL,
    referee_comment VARCHAR(2000) NULL,
    expires_at TIMESTAMP NOT NULL,
    answered_at TIMESTAMP NULL,
    consented_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP NULL,
    error_code VARCHAR(60) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_verification_reference_token UNIQUE (token_hash),
    CONSTRAINT fk_verification_reference_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_verification_reference_relationship CHECK (relationship IN
        ('MANAGER', 'PEER', 'REPORT', 'CLIENT', 'TEACHER', 'OTHER')),
    CONSTRAINT chk_verification_reference_status CHECK (status IN ('SENT', 'ANSWERED', 'DECLINED', 'EXPIRED', 'CANCELLED'))
);

CREATE INDEX idx_verification_reference_candidate ON verification_reference_requests (candidate_id, status);
CREATE INDEX idx_verification_reference_expiry ON verification_reference_requests (status, expires_at);

-- Verdicts drafted from a reference name it instead of a source.
ALTER TABLE claim_verdicts
    ADD CONSTRAINT fk_claim_verdicts_reference
    FOREIGN KEY (reference_id) REFERENCES verification_reference_requests (id) ON DELETE CASCADE;
CREATE INDEX idx_claim_verdicts_reference ON claim_verdicts (reference_id);

-- Evidence items of a reference answer (kind REFERENCE_RESPONSE) have neither run nor source.
ALTER TABLE evidence_items ADD COLUMN reference_id BIGINT NULL;
ALTER TABLE evidence_items
    ADD CONSTRAINT fk_evidence_items_reference
    FOREIGN KEY (reference_id) REFERENCES verification_reference_requests (id) ON DELETE CASCADE;
CREATE INDEX idx_evidence_items_reference ON evidence_items (reference_id);
