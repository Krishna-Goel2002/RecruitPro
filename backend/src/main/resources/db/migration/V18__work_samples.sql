-- Work samples (plan 3.2 and 5.6, WP-BE-C): a timed task per job with a behaviourally anchored rubric, assigned
-- to shortlisted or interviewing applications. A rubric criterion linked to a requirement and scored 3 or 4 makes
-- that requirement DEMONSTRATED (evidence tier 3) at the next match.

CREATE TABLE work_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    instructions TEXT NOT NULL,
    time_limit_minutes INTEGER NOT NULL,
    rubric_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_by_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_work_samples_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_work_samples_created_by FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT chk_work_samples_time_limit CHECK (time_limit_minutes > 0),
    CONSTRAINT chk_work_samples_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE INDEX idx_work_samples_job ON work_samples (job_id, id);

CREATE TABLE work_sample_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_sample_id BIGINT NOT NULL,
    application_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    assigned_at TIMESTAMP NOT NULL,
    due_at TIMESTAMP NULL,
    started_at TIMESTAMP NULL,
    submitted_at TIMESTAMP NULL,
    response_text TEXT NULL,
    response_url VARCHAR(500) NULL,
    scores_json TEXT NULL,
    total_score DECIMAL(5,2) NULL,
    scored_by_user_id BIGINT NULL,
    scored_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_work_sample_assignments_sample_application UNIQUE (work_sample_id, application_id),
    CONSTRAINT fk_work_sample_assignments_sample FOREIGN KEY (work_sample_id) REFERENCES work_samples (id),
    CONSTRAINT fk_work_sample_assignments_application FOREIGN KEY (application_id) REFERENCES applications (id),
    CONSTRAINT fk_work_sample_assignments_scored_by FOREIGN KEY (scored_by_user_id) REFERENCES users (id),
    CONSTRAINT chk_work_sample_assignments_status
        CHECK (status IN ('ASSIGNED', 'STARTED', 'SUBMITTED', 'SCORED', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT chk_work_sample_assignments_total
        CHECK (total_score IS NULL OR (total_score >= 1 AND total_score <= 4))
);

CREATE INDEX idx_work_sample_assignments_application ON work_sample_assignments (application_id, assigned_at);
CREATE INDEX idx_work_sample_assignments_status ON work_sample_assignments (status, started_at);
