-- Claim Ledger and verification sources (plan v2, sections 3.1 and 5; WP-VBE).
-- H2 (MODE=PostgreSQL) runs this file in tests: no partial indexes, no ON CONFLICT, JSON is stored as TEXT.
-- Uniqueness of (candidate_id, kind, identifier) among non-revoked sources is enforced by the service.

CREATE TABLE verification_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    identifier VARCHAR(500) NOT NULL,
    display_label VARCHAR(300) NOT NULL,
    ownership_status VARCHAR(20) DEFAULT 'UNPROVEN' NOT NULL,
    ownership_method VARCHAR(30) NULL,
    ownership_checked_at TIMESTAMP NULL,
    ownership_detail VARCHAR(500) NULL,
    challenge_code VARCHAR(64) NOT NULL,
    access_token_enc TEXT NULL,
    token_scopes VARCHAR(200) NULL,
    file_path VARCHAR(500) NULL,
    credential_text TEXT NULL,
    consent_text_version VARCHAR(40) NOT NULL,
    consented_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_verification_sources_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_verification_sources_kind CHECK (kind IN ('GITHUB', 'GITLAB', 'WEBSITE', 'DOCUMENT', 'OPEN_BADGE')),
    CONSTRAINT chk_verification_sources_ownership CHECK (ownership_status IN ('UNPROVEN', 'PENDING', 'PROVEN', 'FAILED')),
    CONSTRAINT chk_verification_sources_method CHECK (ownership_method IS NULL OR ownership_method IN
        ('OAUTH', 'DNS_TXT', 'WELL_KNOWN_FILE', 'PAGE_CODE', 'PROFILE_BIO_CODE', 'ISSUER_SIGNATURE'))
);

CREATE INDEX idx_verification_sources_candidate ON verification_sources (candidate_id, kind);

CREATE TABLE verification_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    status VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    verifier VARCHAR(40) NULL,
    verifier_version VARCHAR(40) NULL,
    requested_by VARCHAR(20) NOT NULL,
    started_at TIMESTAMP NULL,
    finished_at TIMESTAMP NULL,
    error_code VARCHAR(60) NULL,
    usage_json TEXT NULL,
    summary_json TEXT NULL,
    warnings_json TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_verification_runs_source FOREIGN KEY (source_id) REFERENCES verification_sources (id) ON DELETE CASCADE,
    CONSTRAINT fk_verification_runs_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_verification_runs_status CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT chk_verification_runs_requested_by CHECK (requested_by IN ('CANDIDATE', 'SYSTEM'))
);

CREATE INDEX idx_verification_runs_source ON verification_runs (source_id, status);
CREATE INDEX idx_verification_runs_candidate ON verification_runs (candidate_id, created_at);

-- run_id is NULL for ownership proofs (POST /sources/{id}/ownership-check); reference evidence (V22) has neither.
CREATE TABLE evidence_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NULL,
    source_id BIGINT NULL,
    candidate_id BIGINT NOT NULL,
    item_key VARCHAR(40) NOT NULL,
    kind VARCHAR(30) NOT NULL,
    url VARCHAR(1000) NULL,
    title VARCHAR(300) NULL,
    retrieved_at TIMESTAMP NOT NULL,
    content_hash VARCHAR(80) NOT NULL,
    snapshot_path VARCHAR(500) NULL,
    excerpt VARCHAR(1000) NULL,
    attributes_json TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_evidence_items_run FOREIGN KEY (run_id) REFERENCES verification_runs (id) ON DELETE CASCADE,
    CONSTRAINT fk_evidence_items_source FOREIGN KEY (source_id) REFERENCES verification_sources (id) ON DELETE CASCADE,
    CONSTRAINT fk_evidence_items_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_evidence_items_kind CHECK (kind IN ('PROFILE', 'REPOSITORY', 'MANIFEST', 'COMMIT_SUMMARY', 'README',
        'PAGE', 'DOCUMENT', 'BADGE', 'OWNERSHIP_PROOF', 'REFERENCE_RESPONSE'))
);

CREATE INDEX idx_evidence_items_run ON evidence_items (run_id);
CREATE INDEX idx_evidence_items_source ON evidence_items (source_id);
CREATE INDEX idx_evidence_items_candidate ON evidence_items (candidate_id);

-- Append-only; exactly one row per subject + source (or reference) has is_current = TRUE.
CREATE TABLE claim_verdicts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    subject_type VARCHAR(20) NOT NULL,
    subject_id BIGINT NOT NULL,
    claim_type VARCHAR(30) NOT NULL,
    claim_value VARCHAR(1000) NOT NULL,
    source_id BIGINT NULL,
    reference_id BIGINT NULL,
    run_id BIGINT NULL,
    verifier VARCHAR(40) NOT NULL,
    verifier_version VARCHAR(40) NULL,
    verdict VARCHAR(20) NOT NULL,
    ownership_proven BOOLEAN DEFAULT FALSE NOT NULL,
    reasons_json TEXT NULL,
    integrity_notes_json TEXT NULL,
    evidence_item_ids_json TEXT NULL,
    probe_question VARCHAR(500) NULL,
    candidate_status VARCHAR(30) DEFAULT 'AWAITING_CANDIDATE' NOT NULL,
    candidate_note VARCHAR(1000) NULL,
    candidate_responded_at TIMESTAMP NULL,
    is_current BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_claim_verdicts_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdicts_source FOREIGN KEY (source_id) REFERENCES verification_sources (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdicts_run FOREIGN KEY (run_id) REFERENCES verification_runs (id) ON DELETE SET NULL,
    CONSTRAINT chk_claim_verdicts_subject CHECK (subject_type IN ('RESUME_FACT', 'CANDIDATE_CLAIM')),
    CONSTRAINT chk_claim_verdicts_claim_type CHECK (claim_type IN ('SKILL', 'CERTIFICATION', 'EDUCATION', 'EXPERIENCE', 'OTHER')),
    CONSTRAINT chk_claim_verdicts_verdict CHECK (verdict IN ('VERIFIED', 'PARTLY_VERIFIED', 'NOT_FOUND', 'CONTRADICTED', 'NOT_CHECKABLE')),
    CONSTRAINT chk_claim_verdicts_candidate_status CHECK (candidate_status IN
        ('AWAITING_CANDIDATE', 'SHARED', 'HIDDEN', 'WITHDRAWN', 'SUPERSEDED'))
);

CREATE INDEX idx_claim_verdicts_candidate ON claim_verdicts (candidate_id, is_current);
CREATE INDEX idx_claim_verdicts_subject ON claim_verdicts (candidate_id, subject_type, subject_id);
CREATE INDEX idx_claim_verdicts_source ON claim_verdicts (source_id);

-- A recruiter's review applies to the reviewer's organisation only; append-only, the latest row wins.
CREATE TABLE claim_verdict_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verdict_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    decision VARCHAR(20) NOT NULL,
    note VARCHAR(1000) NULL,
    reviewer_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_claim_verdict_reviews_verdict FOREIGN KEY (verdict_id) REFERENCES claim_verdicts (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdict_reviews_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdict_reviews_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_claim_verdict_reviews_decision CHECK (decision IN ('CONFIRM', 'OVERRULE'))
);

CREATE INDEX idx_claim_verdict_reviews_verdict ON claim_verdict_reviews (verdict_id, organization_id);

-- Shadow-mode evaluation labels; one per verdict and labeller (a second label replaces the first).
CREATE TABLE claim_verdict_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verdict_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    labeller_user_id BIGINT NOT NULL,
    label_verdict VARCHAR(20) NOT NULL,
    note VARCHAR(1000) NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_claim_verdict_labels_verdict FOREIGN KEY (verdict_id) REFERENCES claim_verdicts (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdict_labels_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_claim_verdict_labels_user FOREIGN KEY (labeller_user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_claim_verdict_labels_labeller UNIQUE (verdict_id, labeller_user_id),
    CONSTRAINT chk_claim_verdict_labels_verdict CHECK (label_verdict IN
        ('VERIFIED', 'PARTLY_VERIFIED', 'NOT_FOUND', 'CONTRADICTED', 'NOT_CHECKABLE'))
);

CREATE INDEX idx_claim_verdict_labels_org ON claim_verdict_labels (organization_id);

CREATE TABLE organization_verification_settings (
    organization_id BIGINT NOT NULL PRIMARY KEY,
    mode VARCHAR(20) DEFAULT 'SHADOW' NOT NULL,
    connectors_json TEXT NULL,
    updated_by BIGINT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_org_verification_settings_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_org_verification_settings_user FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_org_verification_settings_mode CHECK (mode IN ('SHADOW', 'VISIBLE'))
);

-- GitHub OAuth state: SHA-256 of 32 random bytes, 10-minute expiry, single use.
CREATE TABLE verification_oauth_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_hash VARCHAR(64) NOT NULL,
    candidate_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_verification_oauth_states_hash UNIQUE (state_hash),
    CONSTRAINT fk_verification_oauth_states_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_verification_oauth_states_provider CHECK (provider IN ('GITHUB'))
);

CREATE INDEX idx_verification_oauth_states_expiry ON verification_oauth_states (expires_at);
