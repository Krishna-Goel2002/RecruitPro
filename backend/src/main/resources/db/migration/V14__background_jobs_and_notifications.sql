SELECT 'PARSE_RESUME', id, 'PENDING', 0, 5, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM resume_analyses
WHERE status IN ('PENDING', 'PROCESSING');
