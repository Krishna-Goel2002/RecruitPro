-- D7 / M7: generic background job queue (retry with exponential backoff, attempt cap, dead letter).

CREATE TABLE background_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type VARCHAR(40) NOT NULL,
    entity_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER DEFAULT 0 NOT NULL,
    max_attempts INTEGER DEFAULT 5 NOT NULL,
    run_after TIMESTAMP NOT NULL,
    locked_at TIMESTAMP NULL,
    last_error VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_background_jobs_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'DEAD')),
    CONSTRAINT chk_background_jobs_attempts CHECK (attempts >= 0 AND max_attempts > 0)
);

CREATE INDEX idx_background_jobs_due ON background_jobs (status, run_after);
CREATE INDEX idx_background_jobs_entity ON background_jobs (job_type, entity_id);

-- D13: notification outbox (email) and in-app inbox.

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NULL,
    recipient_user_id BIGINT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    template VARCHAR(60) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER DEFAULT 0 NOT NULL,
    sent_at TIMESTAMP NULL,
    read_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_notifications_channel CHECK (channel IN ('EMAIL', 'IN_APP')),
    CONSTRAINT chk_notifications_status CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED'))
);

CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_user_id, created_at DESC);
CREATE INDEX idx_notifications_status_created ON notifications (status, created_at);

-- Resume analyses waiting for the removed in-process worker are handed to the queue.
