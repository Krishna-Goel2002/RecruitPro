CREATE TABLE candidate_profiles (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    date_of_birth DATE NULL,
    gender VARCHAR(30) NULL,
    address TEXT NULL,
    city VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    country VARCHAR(100) NULL,
    zip_code VARCHAR(20) NULL,
    linkedin_url VARCHAR(500) NULL,
    portfolio_url VARCHAR(500) NULL,
    years_of_experience INT NULL,
    current_company VARCHAR(255) NULL,
    current_designation VARCHAR(255) NULL,
    expected_salary DECIMAL(12,2) NULL,
    notice_period_days INT NULL,
    profile_summary TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_candidate_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_candidate_profiles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_candidate_experience CHECK (years_of_experience IS NULL OR years_of_experience >= 0),
    CONSTRAINT chk_candidate_salary CHECK (expected_salary IS NULL OR expected_salary >= 0),
    CONSTRAINT chk_candidate_notice_period CHECK (notice_period_days IS NULL OR notice_period_days >= 0)
);
