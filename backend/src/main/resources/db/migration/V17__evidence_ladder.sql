-- Candidate claims: tier 0 (SELF_CLAIMED) until a recruiter corroborates them (tier 2).
-- The value column is claim_value because VALUE is a reserved word in H2.
CREATE TABLE candidate_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    claim_type VARCHAR(30) NOT NULL,
    claim_value VARCHAR(1000) NOT NULL,
    evidence_url VARCHAR(500) NULL,
    source_fact_id BIGINT NULL,
    tier VARCHAR(30) DEFAULT 'SELF_CLAIMED' NOT NULL,
    verified_by_user_id BIGINT NULL,
    verified_at TIMESTAMP NULL,
    verification_note VARCHAR(500) NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_candidate_claims_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_candidate_claims_verified_by FOREIGN KEY (verified_by_user_id) REFERENCES users (id),
    CONSTRAINT chk_candidate_claims_type CHECK (claim_type IN ('SKILL', 'CERTIFICATION', 'EDUCATION', 'EXPERIENCE', 'OTHER')),
    CONSTRAINT chk_candidate_claims_tier
        CHECK (tier IN ('SELF_CLAIMED', 'RESUME_STATED', 'CORROBORATED', 'DEMONSTRATED', 'INTERVIEW_VERIFIED'))
);

CREATE INDEX idx_candidate_claims_candidate ON candidate_claims (candidate_id);

-- Match runs become append-only: every run is kept and exactly one per application is current.
ALTER TABLE job_match_runs DROP CONSTRAINT uk_job_match_runs_application;
ALTER TABLE job_match_runs ADD COLUMN is_current BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE job_match_runs ADD COLUMN verified_coverage DECIMAL(5,1) NULL;
ALTER TABLE job_match_runs ADD COLUMN claimed_coverage DECIMAL(5,1) NULL;
ALTER TABLE job_match_runs ADD COLUMN knockouts_verified BOOLEAN NULL;
ALTER TABLE job_match_runs ADD COLUMN requirements_version INTEGER DEFAULT 1 NOT NULL;
ALTER TABLE job_match_runs ADD COLUMN trigger_reason VARCHAR(40) NULL;

UPDATE job_match_runs SET verified_coverage = observed_evidence_coverage;

ALTER TABLE job_match_runs
    ADD CONSTRAINT chk_job_match_runs_verified
    CHECK (verified_coverage IS NULL OR (verified_coverage >= 0 AND verified_coverage <= 100));
ALTER TABLE job_match_runs
    ADD CONSTRAINT chk_job_match_runs_claimed
    CHECK (claimed_coverage IS NULL OR (claimed_coverage >= 0 AND claimed_coverage <= 100));

CREATE INDEX idx_job_match_runs_job_current ON job_match_runs (job_id, is_current, verified_coverage DESC);
CREATE INDEX idx_job_match_runs_application_current ON job_match_runs (application_id, is_current);

-- Runs written before evidence-ladder-3 have no knockout or tier data: re-match every open application.
INSERT INTO background_jobs (job_type, entity_id, status, attempts, max_attempts, run_after, created_at, updated_at)
SELECT 'MATCH_APPLICATION', id, 'PENDING', 0, 5, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM applications
WHERE status IN ('SUBMITTED', 'SHORTLISTED', 'INTERVIEWING', 'REJECTED');
