-- Phase 1 foundation (PostgreSQL 16; also runs on H2 in MODE=PostgreSQL for tests).
-- System metadata table for platform configuration and schema verification.

CREATE TABLE system_metadata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_key VARCHAR(100) NOT NULL,
    property_value VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_system_metadata_property_key UNIQUE (property_key)
);

